def digest(data):
    return hashlib.sha256(data).hexdigest()


def applied():
    """True only when every file is already exactly what this patch writes."""
    for path, (want, _) in FILES.items():
        full = os.path.join(ROOT, path)
        if not os.path.exists(full):
            return False
        with io.open(full, 'rb') as fh:
            if digest(fh.read()) != want:
                return False
    return True


def main():
    if '--check' in sys.argv:
        if applied():
            print('1.0.20 is on the page')
            return 0
        print('1.0.20 is still to be applied')
        return 1
    for path, (want, blob) in FILES.items():
        data = zlib.decompress(base64.b64decode(blob))
        if digest(data) != want:
            sys.exit('the snapshot for %s is damaged' % path)
        full = os.path.join(ROOT, path)
        parent = os.path.dirname(full)
        if parent and not os.path.isdir(parent):
            os.makedirs(parent)
        with io.open(full, 'wb') as fh:
            fh.write(data)
        print('wrote %s (%d bytes)' % (path, len(data)))
    print('now run: python3 dev/build.py')
    return 0


if __name__ == '__main__':
    sys.exit(main())
